const { contextBridge, ipcRenderer } = require('electron');
const subscribe = (channel, callback, map = (_event, value) => value) => {
  if (typeof callback !== 'function') return () => {};
  const listener = (event, value) => callback(map(event, value));
  ipcRenderer.on(channel, listener);
  return () => ipcRenderer.removeListener(channel, listener);
};
contextBridge.exposeInMainWorld('workshop', {
  openWebVersion: preferences => ipcRenderer.invoke('web:open', preferences),
  returnToDesktop: () => ipcRenderer.invoke('web:stop'),
  onWebVersionChanged: callback => subscribe('web:active', callback),
  getDiagnostics: () => ipcRenderer.invoke('diagnostics:get'),
  reportError: report => ipcRenderer.invoke('diagnostics:report', report),
  openDiagnosticsFolder: () => ipcRenderer.invoke('diagnostics:open-folder'),
  exportDiagnostics: () => ipcRenderer.invoke('diagnostics:export'),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setUsername: value => ipcRenderer.invoke('settings:set-username', value),
  setSecret: (name, value) => ipcRenderer.invoke('settings:set-secret', name, value),
  getLocalModels: baseUrl => ipcRenderer.invoke('local-ai:models', baseUrl),
  saveLocalAi: value => ipcRenderer.invoke('local-ai:save', value),
  saveOmniRoute: value => ipcRenderer.invoke('omniroute:save', value),
  testOmniRoute: () => ipcRenderer.invoke('omniroute:test'),
  importLocalGguf: () => ipcRenderer.invoke('local-ai:import-gguf'),
  onLocalAiProgress: callback => subscribe('local-ai:progress', callback),
  getChatGPTStatus: () => ipcRenderer.invoke('chatgpt:status'),
  connectChatGPT: () => ipcRenderer.invoke('chatgpt:connect'),
  disconnectChatGPT: () => ipcRenderer.invoke('chatgpt:disconnect'),
  cancelChatGPTSignIn: () => ipcRenderer.invoke('chatgpt:cancel-sign-in'),
  openChatGPTUsage: () => ipcRenderer.invoke('chatgpt:open-usage'),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  writeClipboard: value => ipcRenderer.invoke('clipboard:write', value),
  searchMods: input => ipcRenderer.invoke('mods:search', input),
  getModDetails: input => ipcRenderer.invoke('mods:details', input),
  resolveRequiredDependencies: input => ipcRenderer.invoke('mods:required-dependencies', input),
  findBestSetup: query => ipcRenderer.invoke('mods:best-setup', query),
  getGameVersions: () => ipcRenderer.invoke('mods:versions'),
  getPopularMods: input => ipcRenderer.invoke('mods:popular', input),
  importModrinthProfile: input => ipcRenderer.invoke('modrinth:import-profile', input),
  importModrinthFile: () => ipcRenderer.invoke('modrinth:import-file'),
  checkCompatibility: project => ipcRenderer.invoke('compatibility:check', project),
  askAI: (turns, context, attachments, requestId) => ipcRenderer.invoke('chat:ask', turns, context, attachments, requestId),
  onChatProgress: callback => subscribe('chat:progress', callback),
  loadProject: () => ipcRenderer.invoke('project:load'),
  saveProject: project => ipcRenderer.invoke('project:save', project),
  listProjects: () => ipcRenderer.invoke('projects:list'),
  createProject: name => ipcRenderer.invoke('projects:create', name),
  switchProject: id => ipcRenderer.invoke('projects:switch', id),
  exportProject: project => ipcRenderer.invoke('project:export', project),
  openLauncher: () => ipcRenderer.invoke('launcher:open'),
  openExternal: url => ipcRenderer.invoke('app:open-external', url),
  toggleFullscreen: () => ipcRenderer.invoke('window:toggle-fullscreen'),
  isFullscreen: () => ipcRenderer.invoke('window:is-fullscreen'),
  toggleMaximized: () => ipcRenderer.invoke('window:toggle-maximized'),
  minimizeWindow: () => ipcRenderer.invoke('window:minimize'),
  closeWindow: () => ipcRenderer.invoke('window:close'),
  isWindowMaximized: () => ipcRenderer.invoke('window:is-maximized'),
  onMaximizedChanged: callback => subscribe('window:maximized-changed', callback, (_event, maximized) => !!maximized),
  onFullscreenChanged: callback => subscribe('window:fullscreen-changed', callback, (_event, fullscreen) => !!fullscreen),
  startVoiceInput: locale => ipcRenderer.invoke('voice:start', locale),
  stopVoiceInput: () => ipcRenderer.invoke('voice:stop'),
  onVoiceInputEvent: callback => subscribe('voice:event', callback)
});
